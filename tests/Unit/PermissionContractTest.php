<?php

namespace Modules\Glitter\Reservation\Tests\Unit;

use Modules\Glitter\Reservation\Module;
use PHPUnit\Framework\TestCase;

class PermissionContractTest extends TestCase
{
    private string $modulePath;

    protected function setUp(): void
    {
        parent::setUp();

        $this->modulePath = dirname(__DIR__, 2);
        require_once $this->modulePath.'/module.php';
    }

    public function test_every_admin_permission_reference_is_declared_by_the_module_catalog(): void
    {
        $module = new Module;
        $declared = [];

        foreach ($module->getPermissions()['categories'] ?? [] as $category) {
            foreach ($category['permissions'] ?? [] as $permission) {
                $declared[] = $module->getIdentifier().'.'.$category['identifier'].'.'.$permission['action'];
            }
        }

        $referenced = $this->collectReferencedPermissions($module);

        $this->assertSame(
            [],
            array_values(array_diff($referenced, $declared)),
            'Every route, layout, menu, and API permission must use an identifier generated by getPermissions().'
        );
        $this->assertContains('glitter-reservation.reservations.read', $declared);
    }

    /** @return list<string> */
    private function collectReferencedPermissions(Module $module): array
    {
        $permissions = [];

        $moduleDefinition = (string) file_get_contents($this->modulePath.'/module.php');
        preg_match_all("/'permission'\\s*=>\\s*'([a-z0-9.-]+)'/", $moduleDefinition, $menuMatches);
        array_push($permissions, ...($menuMatches[1] ?? []));

        foreach (['resources/routes/admin.json', 'resources/layouts/admin/reservation_booking_list.json'] as $relativePath) {
            $this->collectJsonPermissions(
                json_decode((string) file_get_contents($this->modulePath.'/'.$relativePath), true, 512, JSON_THROW_ON_ERROR),
                $permissions
            );
        }

        $apiRoutes = (string) file_get_contents($this->modulePath.'/src/routes/api.php');
        preg_match_all('/permission:admin,([a-z0-9.-]+)/', $apiRoutes, $matches);
        array_push($permissions, ...($matches[1] ?? []));

        $resource = (string) file_get_contents($this->modulePath.'/src/Http/Resources/ReservationResource.php');
        preg_match_all("/'(glitter-reservation|reservation)\\.[a-z0-9.-]+'/", $resource, $matches);
        foreach ($matches[0] ?? [] as $match) {
            $permissions[] = trim($match, "'");
        }

        $permissions = array_values(array_unique($permissions));
        sort($permissions);

        return $permissions;
    }

    /** @param list<string> $permissions */
    private function collectJsonPermissions(mixed $value, array &$permissions, ?string $key = null): void
    {
        if (is_string($value) && in_array($key, ['permission', 'permissions'], true)) {
            $permissions[] = $value;

            return;
        }

        if (! is_array($value)) {
            return;
        }

        foreach ($value as $childKey => $child) {
            $this->collectJsonPermissions($child, $permissions, is_string($childKey) ? $childKey : $key);
        }
    }
}
